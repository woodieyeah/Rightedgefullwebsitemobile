import fs from "node:fs";
import path from "node:path";

const root = process.argv[2];
const packageJson = JSON.parse(fs.readFileSync(path.join(root, "package.json"), "utf8"));
const wanted = {
  ...packageJson.dependencies,
  ...packageJson.devDependencies,
  ...packageJson.peerDependencies,
};
const virtualStore = path.join(root, "node_modules", ".pnpm");
const entries = fs.readdirSync(virtualStore);

for (const [name, version] of Object.entries(wanted)) {
  const candidates = entries
    .map((entry) => path.join(virtualStore, entry, "node_modules", ...name.split("/")))
    .filter((candidate) => fs.existsSync(path.join(candidate, "package.json")));
  const exactTarget = candidates.find((candidate) => {
    const manifest = JSON.parse(fs.readFileSync(path.join(candidate, "package.json"), "utf8"));
    return manifest.version === version;
  });
  const target = exactTarget || candidates[0];
  if (!target) throw new Error(`Missing cached package ${name}@${version}`);

  const link = path.join(root, "node_modules", ...name.split("/"));
  fs.mkdirSync(path.dirname(link), { recursive: true });
  if (!fs.existsSync(link)) {
    fs.symlinkSync(path.relative(path.dirname(link), target), link, "dir");
  }
}

const binDir = path.join(root, "node_modules", ".bin");
fs.mkdirSync(binDir, { recursive: true });
for (const name of Object.keys(wanted)) {
  const packagePath = path.join(root, "node_modules", ...name.split("/"));
  const manifest = JSON.parse(fs.readFileSync(path.join(packagePath, "package.json"), "utf8"));
  const bins =
    typeof manifest.bin === "string"
      ? { [manifest.name.replace(/^@[^/]+\//, "")]: manifest.bin }
      : manifest.bin || {};
  for (const [binName, relativeTarget] of Object.entries(bins)) {
    const link = path.join(binDir, binName);
    if (!fs.existsSync(link)) {
      const target = path.join(packagePath, relativeTarget);
      fs.symlinkSync(path.relative(binDir, target), link, "file");
    }
  }
}
