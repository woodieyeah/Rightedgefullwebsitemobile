/**
 * The CI diagnostic probe must never reach a release build.
 *
 * The simulator smoke test injects a network recorder, an error reporter and a
 * phase marker into dist/index.html. They paint full-screen overlays and log
 * every request, so shipping them would both deface the app and leak traffic
 * detail to users.
 *
 * They are safe by construction -- the probe exists ONLY in the workflow file
 * and is injected into dist/ inside the runner, after `npm run build` and
 * before `cap sync`, so it lives purely in that job's filesystem. This test
 * pins that property so a later refactor cannot quietly move the probe into
 * the app's own source.
 */
import assert from "node:assert/strict";
import { existsSync, readFileSync, readdirSync } from "node:fs";
import { join } from "node:path";
import test from "node:test";

const root = new URL("..", import.meta.url).pathname;
const MARKERS = ["__netlog", "hermes-netlog", "hermes-phase", "hermes-error", "__renderNetlog"];

function walk(dir: string, out: string[] = []): string[] {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    if (entry.name === "node_modules" || entry.name.startsWith(".")) continue;
    const p = join(dir, entry.name);
    if (entry.isDirectory()) walk(p, out);
    else if (/\.(ts|tsx|js|jsx|html|css)$/.test(entry.name)) out.push(p);
  }
  return out;
}

test("no probe marker appears in application source", () => {
  const files = walk(join(root, "src"));
  files.push(join(root, "index.html"));
  for (const f of files) {
    if (!existsSync(f)) continue;
    const text = readFileSync(f, "utf8");
    for (const marker of MARKERS) {
      assert.ok(
        !text.includes(marker),
        `${marker} leaked into ${f.replace(root, "")} -- it must stay CI-only`,
      );
    }
  }
});

test("no probe marker appears in the built bundle", () => {
  const dist = join(root, "dist");
  if (!existsSync(dist)) return; // nothing built in this environment
  for (const f of walk(dist)) {
    const text = readFileSync(f, "utf8");
    for (const marker of MARKERS) {
      assert.ok(
        !text.includes(marker),
        `${marker} is present in the built output ${f.replace(root, "")}`,
      );
    }
  }
});

test("the probe lives in the workflow and is injected after the build", () => {
  const wf = readFileSync(join(root, ".github/workflows/ios-simulator-smoke.yml"), "utf8");
  assert.ok(wf.includes("__netlog"), "the probe is missing from the workflow");
  // Order matters: build -> inject -> cap sync. Injecting before the build
  // would be overwritten; injecting after cap sync would never reach the app.
  const build = wf.indexOf("name: Build the web bundle");
  const inject = wf.indexOf("name: Inject diagnostics into the built page");
  const sync = wf.indexOf("name: Sync the web assets into the iOS app");
  assert.ok(build !== -1 && inject !== -1 && sync !== -1, "a pipeline step is missing");
  assert.ok(build < inject, "the probe must be injected AFTER the web build");
  assert.ok(inject < sync, "the probe must be injected BEFORE cap sync");
});

test("the probe is injected into dist/, which is never committed", () => {
  const wf = readFileSync(join(root, ".github/workflows/ios-simulator-smoke.yml"), "utf8");
  assert.match(wf, /const p='dist\/index\.html'/, "probe target changed");
  // ios/App/App/public is regenerated by cap sync and gitignored, so the probe
  // cannot survive into a committed artefact either.
  const iosIgnore = join(root, "ios/.gitignore");
  if (existsSync(iosIgnore)) {
    assert.match(readFileSync(iosIgnore, "utf8"), /App\/App\/public/);
  }
});
